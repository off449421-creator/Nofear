public class LiteralPractice {
    public static void main(String[] args) {

        
        long bigNumber = 5000000000L;   

        float temperature = 36.6f;

        char copyrightSymbol = '\u00 A9';

    
        System.out.println("------ Literal Practice ------");
        System.out.println("Long Literal Value: " + bigNumber);
        System.out.println("Float Literal Value: " + temperature);
        System.out.println("Unicode Char Literal Value: " + copyrightSymbol);
    }
}
