public class LiteralPractice { 
    
    public static void main(String[] args) {
        
        long bigNumber = 5000000000L;  
        
        float piValue = 3.14f;
        
        char copyrightSymbol = '\u00A9';

        System.out.println("------ Literal Practice ------");
        System.out.println("Long Literal: " + bigNumber);
        System.out.println("Float Literal: " + piValue);
        System.out.println("Unicode Char Literal: " + copyrightSymbol);
    }
}

